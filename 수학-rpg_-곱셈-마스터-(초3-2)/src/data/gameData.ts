export const LEVEL_TITLES: { minLevel: number; title: string }[] = [
  { minLevel: 1, title: '초보 모험가' },
  { minLevel: 5, title: '숙련 모험가' },
  { minLevel: 10, title: '전문 모험가' },
  { minLevel: 20, title: '곱셈 마스터' },
  { minLevel: 30, title: '전설의 수학 영웅' },
];

export function getLevelTitle(level: number): string {
  let title = '초보 모험가';
  for (const t of LEVEL_TITLES) {
    if (level >= t.minLevel) {
      title = t.title;
    }
  }
  return title;
}

export function getExpNeededForNextLevel(level: number): number {
  return 50 + (level - 1) * 35;
}
